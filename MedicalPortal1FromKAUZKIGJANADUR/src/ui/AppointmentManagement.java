    private void btnAddAppointmentActionPerformed(java.awt.event.ActionEvent evt) {                                                  
        String name = txtPatientName.getText().trim();
        String ageStr = txtAge.getText().trim();
        String date = txtDateTime.getText().trim();
        String time = txtDateTime1.getText().trim();
        String type = cmbType.getSelectedItem().toString();

        if (name.isEmpty() || ageStr.isEmpty() || date.isEmpty() || time.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields.", "Missing Information", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int age;
        try {
            age = Integer.parseInt(ageStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Age must be a number.", "Invalid Input", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String[] parts = date.split("/");
        if (parts.length != 3) {
            JOptionPane.showMessageDialog(this, "Date format should be MM/DD/YYYY (example: 11/26/2026).", "Invalid Date", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int month, day, year;
        try {
            month = Integer.parseInt(parts[0].trim());
            day = Integer.parseInt(parts[1].trim());
            year = Integer.parseInt(parts[2].trim());
            if (year < 100) {
                year += 2000;
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Date format should be MM/DD/YYYY (example: 11/26/2026).", "Invalid Date", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Appointment newAppointment = type.equalsIgnoreCase("Online")
            ? new OnlineAppointment(name, age, date + " " + time, "Pending", "General Checkup", "https://telehealth.portal/room/" + name.replaceAll("\\s+", ""))
            : new Appointment(name, age, date + " " + time, "Pending", "General Checkup");

        newAppointment.trackAppointment();

        DefaultTableModel model = (DefaultTableModel) BTN.getModel();
        model.addRow(new Object[]{ name, age, date, time, type });

        calendarFrame.addAppointmentToDay(year, month, day, name + " (" + age + ") - " + time);

        txtPatientName.setText("");
        txtAge.setText("");
        txtDateTime.setText("");
        txtDateTime1.setText("");
        cmbType.setSelectedIndex(0);

        JOptionPane.showMessageDialog(this, "Appointment for " + name + " successfully registered!", "Success", JOptionPane.INFORMATION_MESSAGE);
    }    
    
    
